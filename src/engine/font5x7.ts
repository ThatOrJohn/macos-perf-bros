const GLYPHS = new Map<string, Uint8Array>();
for (const [ch, rows] of Object.entries(SRC)) {
  const bits = rows.replaceAll("/", "");
  GLYPHS.set(ch, Uint8Array.from(bits, (b) => (b === "#" ? 1 : 0)));
}

export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;
export const LINE_H = 9;

export const textWidth = (s: string) => Math.max(0, [...s].length * ADVANCE - 1);

export interface TextOpts {
  /** Drop shadow color, drawn 1 px down-right. */
  shadow?: Color;
  /** Background box behind the text (1 px padding). */
  bg?: Color;
}

/** Draw text with its top-left at (x, y). Returns the width drawn. */
export function drawText(cv: PixelCanvas, x: number, y: number, text: string, color: Color, opts: TextOpts = {}): number {
  const chars = [...text];
  const w = textWidth(text);
  if (opts.bg !== undefined) cv.rect(x - 1, y - 1, w + 2, GLYPH_H + 2, opts.bg);
  const pass = (ox: number, oy: number, c: Color) => {
    chars.forEach((ch, i) => {
      const g = GLYPHS.get(ch.toUpperCase());
      if (!g) return;
      for (let gy = 0; gy < GLYPH_H; gy++) {
        for (let gx = 0; gx < GLYPH_W; gx++) if (g[gy * GLYPH_W + gx]) cv.set(x + i * ADVANCE + gx + ox, y + gy + oy, c);
      }
    });
  };
  if (opts.shadow !== undefined) pass(1, 1, opts.shadow);
  pass(0, 0, color);
  return w;
}

export function drawTextCentered(cv: PixelCanvas, cx: number, y: number, text: string, color: Color, opts: TextOpts = {}): void {
  drawText(cv, Math.round(cx - textWidth(text) / 2), y, text, color, opts);
}

export function drawTextRight(cv: PixelCanvas, right: number, y: number, text: string, color: Color, opts: TextOpts = {}): void {
  drawText(cv, right - textWidth(text), y, text, color, opts);
}
